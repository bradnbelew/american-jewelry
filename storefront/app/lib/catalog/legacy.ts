/**
 * Pieces from the current american.jewelry catalog, defined in code until they are imported
 * into Shopify. Prices and names are the ones published on that site. Photographs are the
 * 2400 CDN masters. These are not proposals.
 */
const usd = (dollars: number) => Math.round(dollars * 100);

const priced = (price: number, stones?: string) => {
  const diamond = !!stones && /diamond/i.test(stones);
  const gem = !!stones && /gemstone/i.test(stones);
  return [
    {
      key: (diamond ? "diamond" : gem ? "gemstone" : "gold") as "diamond" | "gemstone" | "gold",
      name: diamond ? "Diamond" : gem ? "Gemstone" : "Solid gold",
      priceCents: usd(price),
      stones,
      origin: stones ? ("natural" as const) : ("none" as const),
    },
  ];
};

